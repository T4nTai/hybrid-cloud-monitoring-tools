#!/bin/bash
# =============================================================================
# Script: Configure Telegraf on agent VM
# Mục đích: Sinh file /etc/telegraf/telegraf.conf từ template với IP cụ thể
# Yêu cầu: chạy sau setup-agent.sh
#
# Usage:
#   sudo ./configure-telegraf.sh \
#       --hostname vm-a \
#       --central-ip <AZURE-CENTRAL-IP> \
#       --influx-pass <PASSWORD> \
#       --ping-targets "<AWS-VM-B-IP>,<AZURE-CENTRAL-IP>" \
#       --tcp-target "<AWS-VM-B-IP>:80" \
#       --http-target "http://<AWS-VM-B-IP>/"
# =============================================================================

set -euo pipefail

# Defaults
HOSTNAME_VAL=""
CENTRAL_IP=""
INFLUX_PASS="admin123"
PING_TARGETS=""
TCP_TARGET=""
HTTP_TARGET=""
INTERVAL="15s"

# Parse arguments
while [[ $# -gt 0 ]]; do
    case $1 in
        --hostname)     HOSTNAME_VAL="$2"; shift 2 ;;
        --central-ip)   CENTRAL_IP="$2"; shift 2 ;;
        --influx-pass)  INFLUX_PASS="$2"; shift 2 ;;
        --ping-targets) PING_TARGETS="$2"; shift 2 ;;
        --tcp-target)   TCP_TARGET="$2"; shift 2 ;;
        --http-target)  HTTP_TARGET="$2"; shift 2 ;;
        --interval)     INTERVAL="$2"; shift 2 ;;
        *) echo "Unknown option: $1"; exit 1 ;;
    esac
done

# Validate
if [[ -z "$HOSTNAME_VAL" || -z "$CENTRAL_IP" || -z "$PING_TARGETS" ]]; then
    echo "ERROR: Missing required arguments."
    echo "Required: --hostname, --central-ip, --ping-targets"
    echo ""
    echo "Example:"
    echo "  sudo ./configure-telegraf.sh \\"
    echo "    --hostname vm-a \\"
    echo "    --central-ip 20.1.2.3 \\"
    echo "    --influx-pass mypassword \\"
    echo "    --ping-targets '54.1.2.3,20.1.2.3' \\"
    echo "    --tcp-target '54.1.2.3:80' \\"
    echo "    --http-target 'http://54.1.2.3/'"
    exit 1
fi

# Convert comma-separated ping targets to TOML array
PING_URLS=$(echo "$PING_TARGETS" | awk -F',' '{for(i=1;i<=NF;i++){printf "\"%s\"", $i; if(i<NF) printf ", "}}')

echo "======================================================"
echo "Configuring Telegraf"
echo "======================================================"
echo "Hostname:      $HOSTNAME_VAL"
echo "Central IP:    $CENTRAL_IP"
echo "Ping targets:  $PING_TARGETS"
echo "Interval:      $INTERVAL"
echo ""

# Backup existing config
if [[ -f /etc/telegraf/telegraf.conf ]]; then
    sudo cp /etc/telegraf/telegraf.conf /etc/telegraf/telegraf.conf.bak.$(date +%s)
    echo "✓ Backed up existing config"
fi

# Generate config
sudo tee /etc/telegraf/telegraf.conf > /dev/null <<EOF
# =============================================================================
# Telegraf config — generated by configure-telegraf.sh
# Host: $HOSTNAME_VAL
# =============================================================================

[agent]
  interval = "$INTERVAL"
  round_interval = true
  metric_batch_size = 1000
  metric_buffer_limit = 10000
  collection_jitter = "2s"
  flush_interval = "10s"
  hostname = "$HOSTNAME_VAL"
  omit_hostname = false

# ---- Output: InfluxDB trên Azure Central ----
[[outputs.influxdb]]
  urls = ["http://${CENTRAL_IP}:8086"]
  database = "monitoring"
  username = "admin"
  password = "$INFLUX_PASS"
  timeout = "10s"

# ---- Metrics hệ thống ----
[[inputs.cpu]]
  percpu = false
  totalcpu = true
  collect_cpu_time = true
  report_active = false

[[inputs.mem]]

[[inputs.disk]]
  mount_points = ["/"]

[[inputs.net]]

[[inputs.system]]

# ---- ĐO HIỆU NĂNG MẠNG (quan trọng nhất) ----
[[inputs.ping]]
  urls = [$PING_URLS]
  count = 20
  interval = "$INTERVAL"
  ping_interval = 0.2
  method = "native"
  deadline = 10
EOF

# Add net_response if TCP target provided
if [[ -n "$TCP_TARGET" ]]; then
    sudo tee -a /etc/telegraf/telegraf.conf > /dev/null <<EOF

[[inputs.net_response]]
  protocol = "tcp"
  address = "$TCP_TARGET"
  timeout = "5s"
  read_timeout = "5s"
  interval = "$INTERVAL"
EOF
fi

# Add http_response if HTTP target provided
if [[ -n "$HTTP_TARGET" ]]; then
    sudo tee -a /etc/telegraf/telegraf.conf > /dev/null <<EOF

[[inputs.http_response]]
  urls = ["$HTTP_TARGET"]
  method = "GET"
  response_timeout = "5s"
  interval = "$INTERVAL"
EOF
fi

echo "✓ Config written to /etc/telegraf/telegraf.conf"
echo ""

# Test config
echo "Testing config..."
if sudo telegraf --config /etc/telegraf/telegraf.conf --test --input-filter ping 2>&1 | head -20; then
    echo "✓ Config test passed"
fi

echo ""
echo "======================================================"
echo "Telegraf configured! Restart to apply:"
echo "  sudo systemctl restart telegraf"
echo "  sudo systemctl enable telegraf"
echo "  sudo journalctl -u telegraf -f"
echo "======================================================"
